#!/usr/bin/env python3
"""
log_analyzer.py — Post-Flight Telemetry Analyzer for CanSat Mission Data.

Parses CSV logs generated by the Raspberry Pi Pico CanSat on the SD card,
computes flight statistics (apogee, duration, thermal and pressure ranges,
peak g-forces, GPS fixes), and reports anomalies.
"""

import sys
import os
import csv
import math
from typing import Dict, Any, List, Optional


def parse_float(val: Any, default: Optional[float] = None) -> Optional[float]:
    """Safely parse float values from telemetry rows."""
    try:
        if val is None:
            return default
        cleaned = str(val).strip().replace("meters", "").replace("m", "").replace("hPa", "").replace("C", "")
        return float(cleaned)
    except (ValueError, TypeError):
        return default


def analyze_log(file_path: str) -> Dict[str, Any]:
    """
    Analyze a CanSat CSV telemetry file and return flight metrics.

    Expected CSV columns (supports both format variations):
    Time, Temp, Pressure, Altitude, AccelX, AccelY, AccelZ, GyroX, GyroY, GyroZ, Lat, Lon, GPSAlt, Sats
    """
    if not os.path.exists(file_path):
        raise FileNotFoundError(f"Telemetry log file not found: {file_path}")

    times: List[float] = []
    temps: List[float] = []
    pressures: List[float] = []
    altitudes: List[float] = []
    accel_magnitudes: List[float] = []
    gps_fixes: int = 0
    corrupt_rows: int = 0
    total_rows: int = 0

    with open(file_path, "r", encoding="utf-8", errors="ignore") as f:
        reader = csv.reader(f)
        header = None

        for row in reader:
            if not row or all(c.strip() == "" for c in row):
                continue

            # Detect and store header row
            if header is None:
                first_cell = row[0].strip().lower()
                if "time" in first_cell:
                    header = [c.strip().lower() for c in row]
                    continue
                else:
                    # File has no header, use default index mapping
                    header = ["time", "temp", "pressure", "altitude", "ax", "ay", "az", "gx", "gy", "gz", "lat", "lon", "gps_alt", "sats"]

            total_rows += 1
            if len(row) < 4:
                corrupt_rows += 1
                continue

            try:
                # Time
                t = parse_float(row[0])
                if t is not None:
                    times.append(t)

                # Temp
                temp = parse_float(row[1])
                if temp is not None:
                    temps.append(temp)

                # Pressure
                press = parse_float(row[2])
                if press is not None:
                    pressures.append(press)

                # Altitude
                alt = parse_float(row[3])
                if alt is not None:
                    altitudes.append(alt)

                # Accelerometer magnitude
                if len(row) >= 7:
                    ax = parse_float(row[4], 0.0)
                    ay = parse_float(row[5], 0.0)
                    az = parse_float(row[6], 1.0)
                    if ax is not None and ay is not None and az is not None:
                        mag = math.sqrt(ax**2 + ay**2 + az**2)
                        accel_magnitudes.append(mag)

                # GPS fix count
                if len(row) >= 12:
                    lat_str = str(row[10]).strip().lower()
                    lon_str = str(row[11]).strip().lower()
                    if lat_str not in ("n/a", "waiting", "") and lon_str not in ("n/a", "waiting", ""):
                        gps_fixes += 1

            except Exception:
                corrupt_rows += 1

    duration = (max(times) - min(times)) if times else 0.0
    max_alt = max(altitudes) if altitudes else 0.0
    min_alt = min(altitudes) if altitudes else 0.0
    apogee_gain = max_alt - min_alt

    return {
        "total_samples": total_rows,
        "valid_samples": len(times),
        "corrupt_rows": corrupt_rows,
        "duration_seconds": round(duration, 2),
        "temperature": {
            "min": round(min(temps), 2) if temps else None,
            "max": round(max(temps), 2) if temps else None,
            "avg": round(sum(temps) / len(temps), 2) if temps else None,
        },
        "pressure_hpa": {
            "min": round(min(pressures), 2) if pressures else None,
            "max": round(max(pressures), 2) if pressures else None,
            "avg": round(sum(pressures) / len(pressures), 2) if pressures else None,
        },
        "altitude_m": {
            "apogee": round(max_alt, 2),
            "launch_alt": round(min_alt, 2),
            "apogee_gain": round(apogee_gain, 2),
        },
        "peak_g_force": round(max(accel_magnitudes), 2) if accel_magnitudes else None,
        "gps_fixes_logged": gps_fixes,
    }


def print_summary(report: Dict[str, Any], filepath: str) -> None:
    """Print a clean CLI summary of the telemetry report."""
    print("\n" + "=" * 55)
    print(f"  CANSAT FLIGHT TELEMETRY REPORT: {os.path.basename(filepath)}")
    print("=" * 55)
    print(f"Total Samples Logged:    {report['total_samples']}")
    print(f"Valid Telemetry Frames:  {report['valid_samples']}")
    print(f"Corrupt / Skipped Rows:  {report['corrupt_rows']}")
    print(f"Total Flight Duration:   {report['duration_seconds']} seconds")
    print("-" * 55)
    print("ALTITUDE & APOGEE:")
    print(f"  Peak Altitude (Apogee):{report['altitude_m']['apogee']} m")
    print(f"  Base Altitude:         {report['altitude_m']['launch_alt']} m")
    print(f"  Max Height Gain:       {report['altitude_m']['apogee_gain']} m")
    print("-" * 55)
    print("ENVIRONMENTAL CONDITIONS:")
    if report["temperature"]["avg"] is not None:
        print(f"  Temperature:           {report['temperature']['min']} °C to {report['temperature']['max']} °C (Avg: {report['temperature']['avg']} °C)")
    if report["pressure_hpa"]["avg"] is not None:
        print(f"  Pressure:              {report['pressure_hpa']['min']} hPa to {report['pressure_hpa']['max']} hPa (Avg: {report['pressure_hpa']['avg']} hPa)")
    print("-" * 55)
    print("DYNAMICS & GPS:")
    if report["peak_g_force"] is not None:
        print(f"  Peak Total G-Force:    {report['peak_g_force']} g")
    print(f"  GPS Fixes Achieved:    {report['gps_fixes_logged']}")
    print("=" * 55 + "\n")


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print("Usage: python log_analyzer.py <path_to_cansat_log.csv>")
        print("\nExample: python tools/log_analyzer.py cansat_log.csv")
        sys.exit(1)

    target_file = sys.argv[1]
    try:
        summary = analyze_log(target_file)
        print_summary(summary, target_file)
    except Exception as err:
        print(f"Error analyzing log: {err}")
        sys.exit(1)
